export function scenePaintChoice(mark,level,seed){
 const pool=paintPools[level];
 return {
   recipe:paintRecipes.some(x=>x.id===mark.paintRecipe)?mark.paintRecipe:pool[seed%pool.length],
   palette:paintPalettes.find(x=>x.id===mark.paintPalette)??paintPalettes[(seed>>>5)%paintPalettes.length]
 };
}

const paths=new Map();
export function recipeStroke(ctx,id,colors,x,y,r,progress,seed){
 const [geometry,style]=motifs[Number(id.slice(1))-1]??motifs[0];
 const scale=r/112;
 if(!paths.has(geometry))paths.set(geometry,new Path2D(geometry));
 const path=paths.get(geometry);
 ctx.save();ctx.translate(x,y);ctx.scale(scale,scale);
 ctx.rotate((seed%25-12)*Math.PI/180);
 ctx.beginPath();ctx.rect(-120,-85,240*progress,170);ctx.clip();
 ctx.lineCap='round';ctx.lineJoin='round';ctx.strokeStyle=colors[1];ctx.fillStyle=colors[0];
 ctx.globalAlpha*=.73;
 switch(style){
   case 'fill':case 'stencil':case 'extrude':
     if(style==='extrude'){ctx.save();ctx.translate(8,9);ctx.fillStyle='#24213c';ctx.fill(path);ctx.restore();}
     ctx.fill(path);ctx.lineWidth=style==='stencil'?3:7;ctx.stroke(path);break;
   case 'dots':
     for(let i=0;i<18;i++){const dx=-86+i*10,dy=Math.sin(i)*18;ctx.beginPath();ctx.arc(dx,dy,2+i%6,0,Math.PI*2);ctx.fill();}
     break;
   case 'rainbow':case 'chrome':case 'neon':
     for(let i=0;i<3;i++){ctx.strokeStyle=colors[i];ctx.lineWidth=[17,10,3][i];ctx.stroke(path);}
     break;
   default:
     ctx.lineWidth={mist:22,wide:15,outline:3,drip:5,stroke:7}[style]??6;
     if(style==='mist'){ctx.globalAlpha*=.45;ctx.setLineDash([3,7]);}
     ctx.stroke(path);
 }
 ctx.restore();
}
