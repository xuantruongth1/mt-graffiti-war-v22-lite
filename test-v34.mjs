import assert from 'node:assert/strict';
import {loadConfig,session,ingest,tick} from './engine.mjs';
import {paintPalettes,paintRecipes,paintPools} from './paint-recipes.mjs';
const c=loadConfig({smartWall:true,directPaint:true,idlePan:false});
const t=1_000_000;
const send=(s,type,uid,at=t,coins=0)=>ingest(s,c,type,{userId:uid,nickname:uid,msgId:type+'-'+uid,comment:'Vẽ',diamondCount:coins},at);
const s=session();
assert.equal(c.drawViewers,true);
send(s,'member','viewer');
send(s,'member','promoted');
send(s,'chat','promoted',t+100);
send(s,'chat','comment',t+150);
assert.equal(s.queue.length,3);
assert.equal(s.queue.find(x=>x.uid==='promoted').viewer,false);
assert.equal(Object.hasOwn(s.scores,'viewer'),false);
tick(s,c,t+700);
assert.equal(s.scene.uid,'promoted');
tick(s,{...c,drawViewers:false},s.scene.end+200);
assert(!s.queue.some(x=>x.viewer));
const q=session();
send(q,'gift','small',t,1);
send(q,'gift','same-tier',t+40,105);
send(q,'gift','larger',t+80,490);
tick(q,c,t+510);
assert.equal(q.wallMode,'community');
for(let n=t+580;!q.scene&&n<t+6000;n+=25)tick(q,c,n);
assert.equal(q.scene.uid,'larger');
assert.equal(q.queue.length,2);
assert.equal(paintPalettes.length,16);
assert.equal(paintRecipes.length,28);
assert.equal(new Set(paintRecipes.map(x=>x.algorithm)).size,28);
assert(paintPools.flat().every(id=>paintRecipes.some(recipe=>recipe.id===id)));
console.log('PASS V3.4 viewer mặc định, nâng hàng chờ khi bình luận, bật/tắt, quà cùng bậc ưu tiên theo xu và dữ liệu 28/16.');
